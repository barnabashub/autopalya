export function pickLang(requested) {
  const cands = [requested, ...(navigator.languages || [navigator.language || 'hu'])];
  for (const c of cands) {
    if (!c) continue;
    const base = c.toLowerCase().split('-')[0];
    if (S[base]) return base;
  }
  return 'en';
}

export function makeT(lang) {
  const dict = S[lang] || S.en;
  return (key, vars = {}) => {
    const s = dict[key] ?? S.hu[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  };
}

export function missingKeys() {
  const ref = Object.keys(S.hu);
  const out = {};
  for (const [lang, dict] of Object.entries(S)) {
    const miss = ref.filter((k) => !(k in dict));
    const extra = Object.keys(dict).filter((k) => !(k in S.hu));
    if (miss.length || extra.length) out[lang] = { miss, extra };
  }
  return out;
}
